"""BTC-044 bounded *synthetic-only* local fixture verifier.

Only accepts exact, predetermined bytes of fixtures generated by BTC-036.
This is NOT a general CSV/ZIP verifier or real-market data authenticator.
No network, Binance, strategies, or orders.
"""
import csv
from decimal import Decimal, InvalidOperation
import hashlib
import io
import json
import os
import errno
import secrets
from pathlib import Path
import stat
import zipfile

from .synthetic_fixture_generator import LABEL, fixture_bytes, sha256
from .synthetic_fixture_spec import CSV_SHA256, JSONL_SHA256, SCHEMA

MAX_LOCAL_FILE_BYTES = 200_000
ALLOWED_INPUTS = frozenset({"golden.csv", "golden.zip"})
VERSION = "BTC-044-v1"

class SyntheticVerificationError(ValueError):
    def __init__(self, code):
        super().__init__(code)
        self.code = code


def _fail(code):
    raise SyntheticVerificationError(code)


def _safe_read(root, filename, limit=MAX_LOCAL_FILE_BYTES):
    """Restrict synthetic reads to one regular file under a controlled root.

    On POSIX use directory-descriptor-relative no-follow opens. This is
    defense-in-depth, NOT proof of OS sandboxing or hostile-root safety.
    """
    root = Path(root)
    if not isinstance(filename, str) or filename not in ALLOWED_INPUTS:
        _fail("SYNTHETIC_FILE_NOT_ALLOWED")
    if not root.is_absolute() or not root.is_dir() or root.is_symlink():
        _fail("INPUT_OUTSIDE_ROOT")
    if any(parent.is_symlink() for parent in root.parents):
        _fail("INPUT_OUTSIDE_ROOT")
    if not isinstance(limit, int) or limit <= 0 or limit > MAX_LOCAL_FILE_BYTES:
        _fail("RAW_SIZE_EXCEEDED")
    directory_flags = os.O_RDONLY | getattr(os, "O_DIRECTORY", 0) | getattr(os, "O_NOFOLLOW", 0)
    root_fd = None
    fd = None
    try:
        root_fd = os.open(root, directory_flags)
        if not stat.S_ISDIR(os.fstat(root_fd).st_mode):
            _fail("INPUT_OUTSIDE_ROOT")
        flags = os.O_RDONLY | getattr(os, "O_NOFOLLOW", 0) | getattr(os, "O_NONBLOCK", 0)
        if os.name == "posix":
            fd = os.open(filename, flags, dir_fd=root_fd)
        else:
            # Windows cannot use dir_fd here; explicitly no claim of
            # equivalent OS-level confinement is made.
            fd = os.open(root / filename, flags)
        initial = os.fstat(fd)
        if not stat.S_ISREG(initial.st_mode):
            _fail("INPUT_SYMLINK_OR_SPECIAL")
        if initial.st_size > limit:
            _fail("RAW_SIZE_EXCEEDED")
        pieces = []
        remaining = limit
        while remaining >= 0:
            chunk = os.read(fd, min(8192, remaining + 1))
            if not chunk:
                break
            if len(chunk) > remaining:
                _fail("RAW_SIZE_EXCEEDED")
            pieces.append(chunk)
            remaining -= len(chunk)
        final = os.fstat(fd)
        if (initial.st_dev, initial.st_ino, initial.st_size, initial.st_mtime_ns) != (
            final.st_dev, final.st_ino, final.st_size, final.st_mtime_ns
        ):
            _fail("INPUT_CHANGED")
        data = b"".join(pieces)
        if len(data) != initial.st_size:
            _fail("INPUT_CHANGED")
        return data
    except OSError as exc:
        if exc.errno in (errno.ELOOP, errno.EISDIR, errno.ENOTDIR, errno.ENOENT, errno.EACCES):
            _fail("INPUT_SYMLINK_OR_SPECIAL")
        _fail("INPUT_IO_ERROR")
    finally:
        if fd is not None:
            os.close(fd)
        if root_fd is not None:
            os.close(root_fd)

def _csv_canonical(data):
    if len(data) > MAX_LOCAL_FILE_BYTES or b"\r" in data or b"\x00" in data:
        _fail("CSV_INVALID_ENCODING")
    try:
        text = data.decode("utf-8", "strict")
    except UnicodeError:
        _fail("CSV_INVALID_ENCODING")
    if not text.endswith("\n") or text.startswith("\ufeff"):
        _fail("CSV_INVALID_ENCODING")
    # Bound individual physical rows before the CSV parser materializes fields.
    # Synthetic-candle4h-v1 numeric data never needs CSV quoting or multiline rows.
    for rawline in data.split(b"\n"):
        if len(rawline) > 4096:
            _fail("ROW_TOO_LARGE")
    if b'"' in data:
        _fail("CSV_INVALID_ENCODING")
    try:
        rows = list(csv.reader(io.StringIO(text, newline=""), strict=True))
    except csv.Error:
        _fail("CSV_INVALID_ENCODING")
    if not rows or rows[0] != SCHEMA["column_order"]:
        _fail("CSV_FIELD_COUNT")
    if len(rows) != 3:
        _fail("SYNTHETIC_ROW_COUNT")
    canonical = []
    previous = None
    for raw in rows[1:]:
        if any(len(item.encode("utf8")) > 4096 for item in raw):
            _fail("ROW_TOO_LARGE")
        if len(raw) != 6:
            _fail("CSV_FIELD_COUNT")
        try:
            instant = int(raw[0])
            if raw[0] != str(instant) or instant % 14_400_000:
                _fail("UTC_4H_MISALIGNED")
            if previous is not None and instant - previous != 14_400_000:
                _fail("CANDLE_DUPLICATE_OR_GAP")
            previous = instant
            nums = []
            for val in raw[1:]:
                if not val or val[0] == "+" or "e" in val.lower() or any(ch not in "0123456789." for ch in val):
                    _fail("OHLCV_INVALID")
                number = Decimal(val)
                if not number.is_finite():
                    _fail("OHLCV_INVALID")
                nums.append(number)
            o, hi, lo, cl, vol = nums
            if min(o, hi, lo, cl) <= 0 or vol < 0 or lo > min(o, cl) or hi < max(o, cl):
                _fail("OHLCV_INVALID")
        except SyntheticVerificationError:
            raise
        except (ValueError, InvalidOperation):
            _fail("OHLCV_INVALID")
        canonical.append(dict(zip(SCHEMA["column_order"], [instant] + [format(n.normalize(), "f").rstrip("0").rstrip(".") if n != n.to_integral() else format(n, "f") for n in nums])))
    # Use frozen golden canonical bytes, not a generalized source decoder.
    result = "".join(json.dumps(row, separators=(",", ":"), ensure_ascii=True) + "\n" for row in canonical).encode("utf8")
    return result


def _zip_csv(data):
    try:
        with zipfile.ZipFile(io.BytesIO(data)) as archive:
            members = archive.infolist()
            if len(members) != 1:
                _fail("ZIP_ENTRY_COUNT")
            member = members[0]
            mode = (member.external_attr >> 16) & 0o170000
            if member.filename != "invented.csv" or mode != stat.S_IFREG:
                _fail("ZIP_UNSAFE_MEMBER")
            if member.flag_bits & 1 or member.compress_type not in (zipfile.ZIP_STORED,):
                _fail("ZIP_UNSUPPORTED_COMPRESSION")
            if member.file_size > MAX_LOCAL_FILE_BYTES or member.compress_size > MAX_LOCAL_FILE_BYTES:
                _fail("ZIP_EXPANSION_EXCEEDED")
            if member.compress_size == 0 and member.file_size > 0:
                _fail("ZIP_EXPANSION_EXCEEDED")
            if member.compress_size > 0 and member.file_size > member.compress_size * 100:
                _fail("ZIP_EXPANSION_EXCEEDED")
            with archive.open(member) as entry:
                unpacked = entry.read(MAX_LOCAL_FILE_BYTES + 1)
                if len(unpacked) > MAX_LOCAL_FILE_BYTES:
                    _fail("ZIP_EXPANSION_EXCEEDED")
            return unpacked
    except (zipfile.BadZipFile, RuntimeError, EOFError, OSError):
        _fail("ZIP_BAD_CRC")


def verify_generated(root, filename):
    """Verify a known BTC-036 fixture; do not accept user-supplied arbitrary data."""
    known = fixture_bytes()
    if filename not in ALLOWED_INPUTS or filename not in known:
        _fail("SYNTHETIC_FILE_NOT_ALLOWED")
    # Binding to source-controlled invented bytes is essential. The manifest
    # alone would be attacker-controlled and cannot authorize real datasets.
    raw = _safe_read(root, filename)
    if sha256(raw) != sha256(known[filename]):
        _fail("HASH_MISMATCH")
    csv_bytes = _zip_csv(raw) if filename.endswith(".zip") else raw
    if hashlib.sha256(csv_bytes).hexdigest() != CSV_SHA256:
        _fail("HASH_MISMATCH")
    canonical = _csv_canonical(csv_bytes)
    if sha256(canonical) != JSONL_SHA256:
        _fail("CANONICAL_HASH_MISMATCH")
    return {
        "program": VERSION,
        "status": "SYNTHETIC_INTEGRITY_ONLY",
        "provenance": LABEL,
        "filename": filename,
        "raw_sha256": sha256(raw),
        "canonical_sha256": sha256(canonical),
        "content_integrity_verified": True,
        "publisher_provenance_verified": False,
        "real_market_data_verified": False,
        "h01_backtesting_authorized": False,
        "trading_authorized": False,
    }


def write_report_new(output, result):
    """Exclusive, staged synthetic report publication.

    POSIX: write/fsync hidden temp in a parent directory descriptor, then
    hard-link it to a new destination name (no overwrite), unlink staging.
    This is NOT a hardened OS sandbox or race-proof ancestor validation.
    Windows keeps the original, less-assured exclusive-create behavior.
    """
    dest = Path(output)
    if (not dest.is_absolute() or dest.name in ("", ".", "..")
            or not dest.parent.is_dir() or dest.parent.is_symlink()
            or any(parent.is_symlink() for parent in dest.parent.parents)
            or dest.is_symlink()):
        _fail("REPORT_PATH_COLLISION")
    payload = (json.dumps(result, indent=2, sort_keys=True, allow_nan=False) + "\n").encode("utf8")
    if os.name != "posix":
        try:
            with dest.open("xb") as stream:
                stream.write(payload)
        except (FileExistsError, IsADirectoryError):
            _fail("REPORT_PATH_COLLISION")
        except OSError:
            _fail("REPORT_IO_ERROR")
        return sha256(payload)

    directory_fd = None
    staging_fd = None
    staging_name = None
    try:
        directory_fd = os.open(dest.parent, os.O_RDONLY | os.O_DIRECTORY | getattr(os, "O_NOFOLLOW", 0))
        if not stat.S_ISDIR(os.fstat(directory_fd).st_mode):
            _fail("REPORT_PATH_COLLISION")
        staging_name = ".btc053-" + secrets.token_hex(12) + ".tmp"
        staging_fd = os.open(
            staging_name,
            os.O_WRONLY | os.O_CREAT | os.O_EXCL | getattr(os, "O_NOFOLLOW", 0),
            0o600, dir_fd=directory_fd,
        )
        remaining = memoryview(payload)
        while remaining:
            written = os.write(staging_fd, remaining[:8192])
            if written <= 0:
                _fail("REPORT_IO_ERROR")
            remaining = remaining[written:]
        os.fsync(staging_fd)
        os.close(staging_fd)
        staging_fd = None
        # Hard-link creation is atomic and refuses an existing destination,
        # including a symbolic link, while preserving staged file contents.
        os.link(staging_name, dest.name, src_dir_fd=directory_fd, dst_dir_fd=directory_fd, follow_symlinks=False)
        os.unlink(staging_name, dir_fd=directory_fd)
        staging_name = None
        return sha256(payload)
    except FileExistsError:
        _fail("REPORT_PATH_COLLISION")
    except OSError:
        _fail("REPORT_IO_ERROR")
    finally:
        if staging_fd is not None:
            os.close(staging_fd)
        if directory_fd is not None:
            if staging_name is not None:
                try:
                    os.unlink(staging_name, dir_fd=directory_fd)
                except FileNotFoundError:
                    pass
            os.close(directory_fd)
